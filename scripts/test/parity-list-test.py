#!/usr/bin/env -S python3 -I
# Usage: python3 -I scripts/test/parity-list-test.py
import contextlib
import importlib.util
import io
import json
import sys
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

SCRIPT = Path(__file__).resolve().parent.parent / "parity-list.py"
sys.dont_write_bytecode = True


def page(kind="Read", fields="| `--name` | `string` |  |", name="list-things"):
    return ("<!-- Code generated by vngcloud gen-docs. DO NOT EDIT. -->\n\n# CLI: Things\n\n"
            f"## {name}\n\nKind: {kind}.\n\n"
            + (f"| Flag | Type | Required |\n|-|-|-|\n{fields}\n\n" if fields else "No fields.\n\n")
            + f"```sh\nvngcloud things {name}\n```\n")


class Parity(unittest.TestCase):
    def parse(self, text):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "CLI-Things.md"
            path.write_text(text)
            spec = importlib.util.spec_from_file_location("parity_list", SCRIPT)
            module = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(module)
            return module.parse_page(path)

    def test_baseline_identity_required(self):
        spec = importlib.util.spec_from_file_location("parity_list", SCRIPT)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        errors = io.StringIO()
        with patch.object(sys, "argv", [str(SCRIPT), "/missing"]), contextlib.redirect_stderr(errors):
            with self.assertRaises(SystemExit) as result:
                module.main()
        self.assertNotEqual(result.exception.code, 0)
        self.assertIn("--tag", errors.getvalue())
        self.assertIn("--commit", errors.getvalue())

    def test_read_with_flags(self):
        service = self.parse(page())
        self.assertEqual(service, {"name": "things", "operations": [{"name": "list-things", "kind": "Read", "flags": [{"name": "name", "type": "string", "required": False}]}]})

    def test_write_required(self):
        service = self.parse(page("Write", "| `--id` | `string` | yes |", "create-thing"))
        operation = service["operations"][0]
        self.assertEqual(operation["kind"], "Write")
        self.assertTrue(operation["flags"][0]["required"])

    def test_no_fields(self):
        service = self.parse(page(fields=""))
        self.assertEqual(service["operations"][0]["flags"], [])

    def test_unknown_kind(self):
        with self.assertRaisesRegex(ValueError, r"CLI-Things.md:7:"):
            self.parse(page("Unknown"))

    def test_malformed_row(self):
        with self.assertRaisesRegex(ValueError, r"CLI-Things.md:11:"):
            self.parse(page(fields="| bad | row |"))

    def test_unknown_heading(self):
        with self.assertRaisesRegex(ValueError, r"CLI-Things.md:5:"):
            self.parse(page().replace("## list-things", "### list-things"))

    def test_indented_heading(self):
        with self.assertRaisesRegex(ValueError, r"CLI-Things.md:5:"):
            self.parse(page().replace("## list-things", " ## list-things"))

    def test_duplicate_operation(self):
        operation = page().split("## list-things", 1)[1]
        with self.assertRaisesRegex(ValueError, "duplicate operation"):
            self.parse(page() + "\n## list-things" + operation)

    def test_service_title_mismatch(self):
        with self.assertRaisesRegex(ValueError, "invalid operation example"):
            self.parse(page().replace("vngcloud things", "vngcloud other"))

    def test_indented_wrong_service(self):
        text = page().replace("vngcloud things list-things", "  vngcloud wrong list-things\nvngcloud things list-things")
        with self.assertRaisesRegex(ValueError, "invalid operation example"):
            self.parse(text)

    def test_tab_after_command(self):
        text = page().replace("vngcloud things list-things", "vngcloud\twrong list-things\nvngcloud things list-things")
        with self.assertRaisesRegex(ValueError, "invalid operation example"):
            self.parse(text)

    def test_backslash_followed_by_space(self):
        text = page().replace("vngcloud things list-things", "vngcloud things list-things \\ \nvngcloud wrong list-things")
        with self.assertRaisesRegex(ValueError, "invalid operation example"):
            self.parse(text)

    def test_indented_valid_command(self):
        text = page().replace("vngcloud things list-things", "  vngcloud things list-things")
        with self.assertRaisesRegex(ValueError, "invalid operation example"):
            self.parse(text)

    def test_example_continuation(self):
        text = page().replace("vngcloud things list-things", "vngcloud things list-things \\\n  --name value")
        self.assertEqual(self.parse(text)["name"], "things")

    def test_json_only_field(self):
        operation = self.parse(page(fields="| `Config` (via `--cli-input-json` only) | `string` | yes |"))["operations"][0]
        self.assertEqual(operation["flags"], [])
        self.assertEqual(operation["json_fields"], [{"name": "Config", "type": "string", "required": True}])

    def test_unknown_section(self):
        with self.assertRaisesRegex(ValueError, r"CLI-Things.md:17:"):
            self.parse(page() + "\n```json\n{}\n```\n")


class PageSource(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.repo = self.root / "repo"
        self.wiki = self.repo / "docs/wiki"
        self.wiki.mkdir(parents=True)
        self.pages = [(Path("docs/wiki/CLI-Things.md"), page()),
                      (Path("docs/wiki/CLI-Other.md"), page().replace("Things", "Other").replace("things", "other"))]
        for path, text in self.pages:
            (self.repo / path).write_text(text, encoding="utf-8")
        self.commit = "a" * 40
        spec = importlib.util.spec_from_file_location("parity_list", SCRIPT)
        self.module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(self.module)
        self.output = self.root / "commands.json"

        self.calls = []

    def check_output(self, command, *, env):
        for key in ("GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE"):
            self.assertFalse(key in env, key)
        self.assertEqual(command[:3], ["git", "-C", str(self.repo)])
        args = command[3:]
        self.calls.append(args)
        if args == ["rev-parse", "HEAD"]:
            return (self.commit + "\n").encode()
        if args == ["ls-tree", "-rz", "--name-only", self.commit, "--", "docs/wiki"]:
            return b"docs/wiki/CLI-Things.md\0docs/wiki/CLI-Other.md\0docs/wiki/Other.md\0"
        blobs = {f"{self.commit}:{path}": text.encode("utf-8") for path, text in self.pages}
        if len(args) == 2 and args[0] == "show" and args[1] in blobs:
            return blobs[args[1]]
        self.fail(f"unexpected Git arguments: {args}")

    def run_list(self, *args, commit=None):
        argv = [str(SCRIPT), str(self.repo), "--tag", "test", "--commit", commit or self.commit, *args]
        hostile = {"GIT_DIR": "/wrong", "GIT_WORK_TREE": "/wrong", "GIT_INDEX_FILE": "/wrong"}
        with patch.object(sys, "argv", argv), patch.object(self.module, "OUTPUT", self.output), \
             patch.dict(self.module.os.environ, hostile), \
             patch.object(self.module.subprocess, "check_output", side_effect=self.check_output):
            return self.module.main()

    def test_git_environment_isolated(self):
        hostile = {"GIT_DIR": "/wrong", "GIT_WORK_TREE": "/wrong", "GIT_INDEX_FILE": "/wrong"}
        with patch.dict(self.module.os.environ, hostile):
            source = self.module.GitBaseline(self.repo)
        for key in hostile:
            self.assertFalse(key in source.env, key)

    def test_commit_mismatch(self):
        self.assertEqual(self.run_list(commit="0" * 40), 1)
        self.assertFalse(self.output.exists())

    def test_stale_output(self):
        self.assertEqual(self.run_list(), 0)
        self.output.write_bytes(b"stale\n")
        self.assertEqual(self.run_list("--check"), 1)
        self.assertEqual(self.output.read_bytes(), b"stale\n")

    def test_crlf_output(self):
        self.assertEqual(self.run_list(), 0)
        canonical = self.output.read_bytes()
        self.output.write_bytes(canonical.replace(b"\n", b"\r\n"))
        self.assertEqual(self.run_list("--check"), 1)

    def test_ignores_working_tree_changes(self):
        self.assertEqual(self.run_list(), 0)
        canonical = self.output.read_bytes()
        (self.wiki / "CLI-Things.md").unlink()
        self.assertEqual(self.run_list("--check"), 0)
        self.assertEqual(self.output.read_bytes(), canonical)
        self.assertEqual([service["name"] for service in json.loads(canonical)["services"]], ["other", "things"])
        expected = [["rev-parse", "HEAD"], ["ls-tree", "-rz", "--name-only", self.commit, "--", "docs/wiki"],
                    ["show", f"{self.commit}:docs/wiki/CLI-Other.md"],
                    ["show", f"{self.commit}:docs/wiki/CLI-Things.md"]]
        self.assertEqual(self.calls, expected * 2)


if __name__ == "__main__":
    unittest.main()
