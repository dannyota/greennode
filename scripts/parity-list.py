#!/usr/bin/env -S python3 -I
# Usage: python3 -I scripts/parity-list.py <baseline-dir> --tag <tag> --commit <commit> [--check]
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "crates/greennode/tests/parity/commands.json"
KINDS = {"Read", "Write", "Write, destructive", "Read, local replacement requires --yes", "Write, replacement requires --yes"}
NAME = r"[a-z0-9]+(?:-[a-z0-9]+)*"
ROW = re.compile(r"\| (`--(" + NAME + r")`|`([A-Za-z][A-Za-z0-9]*)` \(via `--cli-input-json` only\)) \| `([^`|]+)` \| (yes)? \|")


def parse_page(path, text=None):
    lines = (path.read_text(encoding="utf-8") if text is None else text).splitlines()

    def fail(index, message):
        raise ValueError(f"{path}:{index + 1}: {message}")

    if not lines or lines[0] != "<!-- Code generated by vngcloud gen-docs. DO NOT EDIT. -->":
        fail(0, "missing generated marker")
    if len(lines) < 3 or not re.fullmatch(r"# CLI: [A-Za-z]+", lines[2]):
        fail(2, "invalid page title")
    title = lines[2][7:]
    if path.name != f"CLI-{title}.md":
        fail(2, "page title does not match filename")
    expected_service = title.lower()
    headings = []
    seen = set()
    for i, line in enumerate(lines[3:], 3):
        if line.lstrip().startswith("#"):
            match = re.fullmatch(r"## (" + NAME + r")", line)
            if not match:
                fail(i, "unrecognized heading")
            if match.group(1) in seen:
                fail(i, "duplicate operation")
            seen.add(match.group(1))
            headings.append((i, match.group(1)))
        elif not headings and line.lstrip().startswith(("|", "Kind:", "```")):
            fail(i, "unrecognized preamble")
    if not headings:
        fail(len(lines), "no operations")
    service = None
    operations = []
    for n, (start, name) in enumerate(headings):
        end = headings[n + 1][0] if n + 1 < len(headings) else len(lines)
        kind_index = start + 2
        if kind_index >= end or not lines[kind_index].startswith("Kind: ") or not lines[kind_index].endswith("."):
            fail(kind_index, "missing kind")
        kind = lines[kind_index][6:-1]
        if kind not in KINDS:
            fail(kind_index, "unrecognized kind")
        flags = []
        json_fields = []
        found_fields = False
        found_example = False
        i = kind_index + 1
        while i < end:
            line = lines[i]
            if not line:
                i += 1
                continue
            if line == "No fields.":
                if found_fields or found_example:
                    fail(i, "duplicate or misplaced fields")
                found_fields = True
                i += 1
                continue
            if line == "| Flag | Type | Required |":
                if found_fields or found_example:
                    fail(i, "duplicate or misplaced table")
                found_fields = True
                i += 1
                if i >= end or lines[i] != "|-|-|-|":
                    fail(i, "invalid table separator")
                i += 1
                rows = 0
                while i < end and lines[i].startswith("|"):
                    match = ROW.fullmatch(lines[i])
                    if not match:
                        fail(i, "invalid table row")
                    flag, field, typ, required = match.group(2, 3, 4, 5)
                    item = {"name": flag or field, "type": typ, "required": required == "yes"}
                    (flags if flag else json_fields).append(item)
                    rows += 1
                    i += 1
                if not rows:
                    fail(i, "empty table")
                continue
            if line.startswith("```"):
                if line not in {"```sh", "```json"}:
                    fail(i, "unrecognized code block")
                opening = i
                i += 1
                block = []
                while i < end and lines[i] != "```":
                    block.append(lines[i])
                    i += 1
                if i == end:
                    fail(opening, "unterminated code block")
                if found_fields:
                    if found_example or line != "```sh":
                        fail(opening, "unrecognized section after fields")
                    matches = [re.match(r"vngcloud (" + NAME + r") (" + NAME + r")(?:\s|$)", x) for x in block]
                    matches = [m.group(1) for m in matches if m]
                    if not matches or len(set(matches)) != 1 or matches[0] != expected_service or (service is not None and service != matches[0]):
                        fail(opening, "invalid operation example")
                    service = matches[0]
                    found_example = True
                i += 1
                continue
            if line.startswith(("|", "Kind:", "#")) or found_fields:
                fail(i, "unrecognized section")
            i += 1
        if not found_fields or not found_example:
            fail(end, "missing fields or example")
        operation = {"name": name, "kind": kind, "flags": flags}
        if json_fields:
            operation["json_fields"] = json_fields
        operations.append(operation)
    return {"name": service, "operations": operations}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("baseline", type=Path)
    parser.add_argument("--tag", required=True)
    parser.add_argument("--commit", required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        commit = subprocess.check_output(["git", "-C", str(args.baseline), "rev-parse", "HEAD"], text=True).strip()
        if commit != args.commit:
            raise ValueError(f"baseline HEAD is {commit}, expected {args.commit}")
        git = ["git", "-C", str(args.baseline)]
        entries = subprocess.check_output(git + ["ls-tree", "-rz", "--name-only", commit, "--", "docs/wiki"])
        paths = sorted(path for path in entries.decode("utf-8").split("\0")
                       if re.fullmatch(r"docs/wiki/CLI-[^/]+\.md", path))
        if not paths:
            raise ValueError("no baseline service pages")
        services = sorted((parse_page(Path(path), subprocess.check_output(git + ["show", f"{commit}:{path}"]).decode("utf-8"))
                           for path in paths), key=lambda service: service["name"])
        if len({service["name"] for service in services}) != len(services):
            raise ValueError("duplicate service name")
        data = (json.dumps({"tag": args.tag, "commit": args.commit, "services": services}, indent=2) + "\n").encode("utf-8")
        if args.check:
            if not OUTPUT.exists() or OUTPUT.read_bytes() != data:
                raise ValueError(f"{OUTPUT}: differs from baseline")
        else:
            OUTPUT.parent.mkdir(parents=True, exist_ok=True)
            OUTPUT.write_bytes(data)
    except (OSError, subprocess.CalledProcessError, ValueError) as exc:
        print(f"parity-list: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
