use std::collections::HashSet;
use std::fmt::Write as _;
use std::fs;
use std::io::{self, Read};
use std::path::Path;

use crate::cli::op::{Kind, Service};
use crate::services::Registry;

const MARKER: &str = "<!-- Code generated by greennode gen-docs. DO NOT EDIT. -->";

fn title(name: &str) -> String {
    match name {
        "dns" | "cdn" | "iam" | "vks" => name.to_ascii_uppercase(),
        "loadbalancer" => "LoadBalancer".into(),
        "globalloadbalancer" => "GlobalLoadBalancer".into(),
        "containerregistry" => "ContainerRegistry".into(),
        _ => {
            let mut chars = name.chars();
            chars.next().map_or_else(String::new, |c| {
                c.to_uppercase().collect::<String>() + chars.as_str()
            })
        }
    }
}

fn service_page(service: &Service) -> String {
    let mut page = format!("{MARKER}\n\n# CLI: {}\n\n", title(service.name));
    let mut operations: Vec<_> = service.operations.iter().collect();
    operations.sort_by_key(|op| op.name);
    for op in operations {
        let kind = match op.kind {
            Kind::Read => "Read",
            Kind::Write => "Write",
            Kind::DestructiveWrite => "Write, destructive",
            Kind::ReadLocalReplacement => "Read, local replacement requires --yes",
            Kind::WriteReplacement => "Write, replacement requires --yes",
        };
        let _ = write!(page, "## {}\n\nKind: {kind}.\n\n", op.name);
        for note in op.notes {
            let _ = write!(page, "{note}\n\n");
        }
        if op.flags.is_empty()
            && op.inherited_bindings.is_empty()
            && op.json_fields.is_empty()
            && op.extra_flags.is_empty()
        {
            page.push_str("No fields.\n\n");
        } else {
            page.push_str("| Flag | Type | Required |\n|-|-|-|\n");
            for field in op
                .flags
                .iter()
                .chain(op.inherited_bindings.iter().map(|b| &b.flag))
                .chain(op.extra_flags)
            {
                let _ = writeln!(
                    page,
                    "| `--{}` | `{}` | {} |",
                    field.name,
                    field.go_type,
                    if field.required { "yes" } else { "" }
                );
            }
            for field in op.json_fields {
                let _ = writeln!(
                    page,
                    "| `{}` (via `--cli-input-json` only) | `{}` | {} |",
                    field.name,
                    field.go_type,
                    if field.required { "yes" } else { "" }
                );
            }
            page.push('\n');
        }
        let mut example = op.example.map(str::to_owned).unwrap_or_else(|| {
            let mut value = format!("greennode {} {}", service.name, op.name);
            for field in op
                .flags
                .iter()
                .chain(op.inherited_bindings.iter().map(|b| &b.flag))
                .chain(op.extra_flags)
                .filter(|field| field.required)
            {
                let _ = write!(value, " --{} <{}>", field.name, field.name);
            }
            let json_fields: Vec<_> = op
                .json_fields
                .iter()
                .filter(|field| field.required)
                .map(|field| {
                    let placeholder = match field.go_type.trim_start_matches('*') {
                        "string" => "\"value\"",
                        "bool" => "true",
                        "int" | "int64" | "float64" => "1",
                        typ if typ.starts_with("[]") => "[]",
                        _ => "{}",
                    };
                    format!("\"{}\":{placeholder}", field.name)
                })
                .collect();
            if !json_fields.is_empty() {
                let _ = write!(value, " --cli-input-json '{{{}}}'", json_fields.join(","));
            }
            if op.kind == Kind::DestructiveWrite {
                value.push_str(" --yes");
            }
            value
        });
        if !example.ends_with('\n') {
            example.push('\n');
        }
        let _ = write!(page, "```sh\n{example}```\n\n");
    }
    page
}

pub(crate) fn generate(dir: &Path, registry: &Registry) -> io::Result<()> {
    fs::create_dir_all(dir)?;
    let mut services: Vec<_> = registry.services().iter().collect();
    services.sort_by_key(|service| service.name);
    let mut page = format!("{MARKER}\n\n# CLI\n\n## Services\n\n");
    let mut keep = HashSet::new();
    for service in services {
        let name = title(service.name);
        let file = format!("CLI-{name}.md");
        let _ = writeln!(page, "- [{name}]({file})");
        fs::write(dir.join(&file), service_page(service))?;
        keep.insert(file);
    }
    page.push_str("\n## Global flags\n\n| Flag | Meaning |\n|-|-|\n| `--profile` | Profile to use |\n| `--region` | Region to use |\n| `--project-id` | Project ID to use |\n| `--output` | `json`, `table`, or `text`; default from the profile's `output`, else `json` |\n| `--query` | JMESPath expression to filter output |\n| `--yes` | Confirm a destructive operation |\n| `--debug` | Log requests to stderr |\n| `--read-only` | Refuse every write command |\n\n## --cli-input-json\n\nOperations accept an inline JSON object or `file://` followed by a local path, unless the operation disables input JSON. Keys use exact, case-sensitive Go input field names. Explicit flags override JSON. Unknown fields and trailing data are errors.\n\n## Exit codes\n\n| Code | Meaning |\n|-|-|\n| 0 | Success |\n| 1 | API or network error, or a canceled command |\n| 2 | Usage or config error |\n| 3 | No credentials, login failure, or HTTP 401 |\n| 4 | Not found |\n");
    fs::write(dir.join("CLI.md"), page)?;
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        let name = entry.file_name();
        let Some(name) = name.to_str() else { continue };
        if !name.starts_with("CLI-")
            || !name.ends_with(".md")
            || keep.contains(name)
            || !entry.file_type()?.is_file()
        {
            continue;
        }
        let mut prefix = vec![0; MARKER.len()];
        let mut file = fs::File::open(entry.path())?;
        if file.read_exact(&mut prefix).is_ok() && prefix == MARKER.as_bytes() {
            fs::remove_file(entry.path())?;
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generation_is_repeatable_and_removes_only_marked_stale_pages() {
        let dir = std::env::temp_dir().join(format!("greennode-docs-{}", std::process::id()));
        fs::create_dir_all(&dir).unwrap();
        fs::write(dir.join("CLI-Stale.md"), format!("{MARKER}\nold")).unwrap();
        fs::write(dir.join("CLI-Manual.md"), "manual").unwrap();
        let registry = Registry::new(&[]).unwrap();
        generate(&dir, &registry).unwrap();
        let first = fs::read(dir.join("CLI.md")).unwrap();
        assert!(!dir.join("CLI-Stale.md").exists());
        assert!(dir.join("CLI-Manual.md").exists());
        generate(&dir, &registry).unwrap();
        assert_eq!(first, fs::read(dir.join("CLI.md")).unwrap());
        fs::remove_dir_all(dir).unwrap();
    }
    #[test]
    fn global_flag_table_matches_baseline() {
        let dir =
            std::env::temp_dir().join(format!("greennode-docs-golden-{}", std::process::id()));
        generate(&dir, &Registry::new(&[]).unwrap()).unwrap();
        let page = fs::read_to_string(dir.join("CLI.md")).unwrap();
        let expected = "| Flag | Meaning |\n|-|-|\n| `--profile` | Profile to use |\n| `--region` | Region to use |\n| `--project-id` | Project ID to use |\n| `--output` | `json`, `table`, or `text`; default from the profile's `output`, else `json` |\n| `--query` | JMESPath expression to filter output |\n| `--yes` | Confirm a destructive operation |\n| `--debug` | Log requests to stderr |\n| `--read-only` | Refuse every write command |\n";
        assert!(page.contains(expected));
        fs::remove_dir_all(dir).unwrap();
    }
}
